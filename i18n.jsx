const I18nCtx = React.createContext({ t: (k) => k, lang: "en", setLang: () => {}, theme: "light", setTheme: () => {} });

function LangThemeProvider({ children }) {
  const [lang, setLangState] = React.useState(() => localStorage.getItem("lv_lang") || "en");
  const [theme, setThemeState] = React.useState(() => localStorage.getItem("lv_theme") || "light");

  const setLang = (l) => { setLangState(l); localStorage.setItem("lv_lang", l); };
  const setTheme = (th) => {
    setThemeState(th);
    localStorage.setItem("lv_theme", th);
    document.documentElement.setAttribute("data-theme", th);
  };

  React.useEffect(() => {
    document.documentElement.setAttribute("data-theme", theme);
  }, []);

  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  const t = (key) => dict[key] || TRANSLATIONS.en[key] || key;

  return (
    <I18nCtx.Provider value={{ t, lang, setLang, theme, setTheme }}>
      {children}
    </I18nCtx.Provider>
  );
}

function useI18n() { return React.useContext(I18nCtx); }

Object.assign(window, { LangThemeProvider, useI18n });
